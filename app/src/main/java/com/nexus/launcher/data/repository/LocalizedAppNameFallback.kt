    fun getFallbackLabel(packageName: String, languageCode: String): String? {
        return when (languageCode.lowercase()) {
            "ne" -> NEPALI_TITLES[packageName]
            "ar" -> ARABIC_TITLES[packageName]
            "iw", "he" -> HEBREW_TITLES[packageName]
            else -> null
        }
    }
